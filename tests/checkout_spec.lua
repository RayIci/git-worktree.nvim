local H = require("helpers")

describe("creation", function()
  it("creates a new branch at the invoking checkout's HEAD without changing cwd", function()
    local wt = require("git-worktree")
    local linked = H.repo .. ".worktrees/a"
    H.git(H.repo, "worktree", "add", "-q", "-b", "a", linked)
    vim.fn.writefile({ "linked" }, linked .. "/linked.txt")
    H.git(linked, "add", ".")
    H.git(linked, "commit", "-q", "-m", "linked")
    vim.api.nvim_set_current_dir(linked)
    local ctx = wt.discover()
    local path = wt.destination(ctx, "feature/next")
    local tree = wt.create_checkout(ctx, { kind = "new", name = "feature/next", ref = "" }, path)
    eq(path, tree.path)
    eq(ctx.head, H.git(path, "rev-parse", "HEAD"))
    ok(ctx.head ~= H.git(H.repo, "rev-parse", "HEAD"), "started from the linked HEAD")
    eq(linked, vim.fn.getcwd())
  end)

  it("checks out an existing local branch", function()
    local wt = require("git-worktree")
    H.git(H.repo, "branch", "ui/local")
    local ctx = wt.discover()
    local path = wt.destination(ctx, "ui/local")
    wt.create_checkout(ctx, { kind = "local", name = "ui/local", ref = "refs/heads/ui/local" }, path)
    eq("refs/heads/ui/local", H.git(path, "symbolic-ref", "HEAD"))
  end)

  it("tracks a remote branch without fetching", function()
    local wt = require("git-worktree")
    H.git(H.repo, "remote", "add", "upstream", H.root .. "/nonexistent-remote")
    H.git(H.repo, "update-ref", "refs/remotes/upstream/remote/feature", H.git(H.repo, "rev-parse", "HEAD"))
    local ctx = wt.discover()
    local choice = { kind = "remote", name = "remote/feature", ref = "refs/remotes/upstream/remote/feature" }
    local path = wt.destination(ctx, choice.name)
    wt.create_checkout(ctx, choice, path)
    eq("upstream", H.git(path, "config", "branch.remote/feature.remote"))
    eq("refs/heads/remote/feature", H.git(path, "config", "branch.remote/feature.merge"))
  end)

  it("reuses an existing local counterpart of a remote branch without resetting it", function()
    local wt = require("git-worktree")
    local head = H.git(H.repo, "rev-parse", "HEAD")
    H.git(H.repo, "branch", "feature/next")
    vim.fn.writefile({ "newer" }, H.repo .. "/newer.txt")
    H.git(H.repo, "add", ".")
    H.git(H.repo, "commit", "-q", "-m", "newer")
    H.git(H.repo, "update-ref", "refs/remotes/upstream/feature/next", H.git(H.repo, "rev-parse", "HEAD"))
    H.git(H.repo, "remote", "add", "upstream", H.root .. "/nonexistent")
    local ctx = wt.discover()
    local choice = { kind = "remote", name = "feature/next", ref = "refs/remotes/upstream/feature/next" }
    local path = wt.destination(ctx, choice.name)
    wt.create_checkout(ctx, choice, path)
    eq(head, H.git(path, "rev-parse", "HEAD"))
  end)

  it("refuses a branch that is already checked out and an existing new branch", function()
    local wt = require("git-worktree")
    local ctx = wt.discover()
    H.rejects("already checked out", function()
      wt.create_checkout(ctx, { kind = "local", name = "main", ref = "refs/heads/main" }, H.root .. "/unused")
    end)
    H.git(H.repo, "branch", "taken")
    H.rejects("already exists", function()
      wt.create_checkout(ctx, { kind = "new", name = "taken", ref = "" }, H.root .. "/unused")
    end)
    eq(nil, vim.uv.fs_stat(H.root .. "/unused"))
  end)

  it("reports git's own failure", function()
    local wt = require("git-worktree")
    vim.fn.writefile({ "a file" }, H.root .. "/blocked-parent")
    local ctx = wt.discover()
    H.rejects("fatal:", function()
      wt.create_checkout(ctx, { kind = "new", name = "x", ref = "" }, H.root .. "/blocked-parent/worktree")
    end)
    eq(H.repo, vim.fn.getcwd())
  end)

  it("fires GitWorktreeCreated and tells participants", function()
    local wt = require("git-worktree")
    local events, changed = {}, {}
    local id = vim.api.nvim_create_autocmd("User", {
      pattern = "GitWorktreeCreated",
      callback = function(ev)
        events[#events + 1] = ev.data.path
      end,
    })
    wt.register({
      name = "spy",
      changed = function(ctx)
        changed[#changed + 1] = ctx.current
      end,
    })
    local ctx = wt.discover()
    local path = wt.destination(ctx, "evented")
    wt.create_checkout(ctx, { kind = "new", name = "evented", ref = "" }, path)
    vim.api.nvim_del_autocmd(id)
    eq({ path }, events)
    eq({ H.repo }, changed)
  end)
end)

describe("removal", function()
  ---@return string linked, GitWorktreeContext ctx
  local function linked_checkout()
    local wt = require("git-worktree")
    local linked = H.repo .. ".worktrees/old"
    H.git(H.repo, "worktree", "add", "-q", "-b", "old", linked)
    return linked, wt.discover()
  end

  it("removes a clean inactive checkout and keeps its branch", function()
    local linked, ctx = linked_checkout()
    require("git-worktree").remove_checkout(ctx, linked)
    eq(nil, vim.uv.fs_stat(linked))
    eq("refs/heads/old", H.git(H.repo, "for-each-ref", "--format=%(refname)", "refs/heads/old"))
  end)

  it("protects the main and the active checkout, including through an alias", function()
    local wt = require("git-worktree")
    local linked = linked_checkout()
    local alias = H.root .. "/alias"
    assert(vim.uv.fs_symlink(H.repo, alias))
    H.rejects("main or active", function()
      wt.remove_checkout(wt.discover(), alias)
    end)
    vim.api.nvim_set_current_dir(linked)
    H.rejects("main or active", function()
      wt.remove_checkout(wt.discover(), linked)
    end)
  end)

  it("protects modified, staged, untracked, ignored and locked checkouts", function()
    local wt = require("git-worktree")
    local linked, ctx = linked_checkout()
    local function refused(pattern)
      H.rejects(pattern, function()
        wt.remove_checkout(ctx, linked)
      end)
      ok(vim.uv.fs_stat(linked), "checkout still exists")
    end
    vim.fn.writefile({ ".env" }, H.git(H.repo, "rev-parse", "--git-path", "info/exclude"))
    vim.fn.writefile({ "secret" }, linked .. "/.env")
    refused("contains modified")
    vim.fn.delete(linked .. "/.env")
    vim.fn.writefile({ "changed" }, linked .. "/file.txt")
    refused("contains modified")
    H.git(linked, "restore", "file.txt")
    vim.fn.writefile({ "new" }, linked .. "/untracked")
    refused("contains modified")
    H.git(linked, "add", "untracked")
    refused("contains modified")
    H.git(linked, "reset", "-q", "--", "untracked")
    vim.fn.delete(linked .. "/untracked")
    H.git(H.repo, "worktree", "lock", linked)
    refused("locked")
  end)

  it("refuses when the working directory changed since the action started", function()
    local wt = require("git-worktree")
    local linked, ctx = linked_checkout()
    vim.api.nvim_set_current_dir(linked)
    H.rejects("directory changed", function()
      wt.remove_checkout(ctx, linked)
    end)
  end)
end)
